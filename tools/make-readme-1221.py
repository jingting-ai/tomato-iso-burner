def main():
    src = io.open(SRC, encoding='utf-8').read()

    # 1) 标题版本号
    src = src.replace('Doro 镜像刻录工具 v1.2.20 —— 使用说明',
                      'Doro 镜像刻录工具 v1.2.21 —— 使用说明', 1)
    # 2) 原来的「本版改进」降级为「上一版改进」
    src = src.replace('【本版改进：图标看得见了、内置硬盘会二次确认】',
                      '【上一版改进（v1.2.20）：图标看得见了、内置硬盘会二次确认】', 1)
    # 3) 插入新的本版改进段落（放在标题下的分隔线之后）
    sep = '=' * 49
    i = src.index(sep)
    j = src.index('\n', i) + 1
    src = src[:j] + '\n\n' + NEW_SECTION + src[j:]
    # 4) 替换整个目录内容块
    s = src.index('【目录内容】')
    e = src.index('【先搞清楚：')
    src = src[:s] + DIR_BLOCK + '\n\n' + src[e:]

    # 5) 底栏版本号
    src = src.replace('· 程序底栏显示 v1.2.20；', '· 程序底栏显示 v1.2.21；', 1)

    # 6) v1.2.16 那两张对照示意图：顶栏的版本号已经去掉，
    #    用空格顶掉原位置，保持方框宽度不变
    src = src.replace('v1.2.20 …', '        …')
    src = src.replace('· 右侧的状态标签（版本 / 管理员权限）和外观切换按钮会自动给',
                      '· 右侧的状态标签（管理员权限）、「关于」按钮和外观切换按钮会自动给', 1)
    src = src.replace('（此时那个副标题会自动省略）。', '。', 1)

    # 7)「关于」入口位置的描述
    src = src.replace('· 界面顶栏最右侧的「♡ 关于」按钮',
                      '· 界面顶栏右上角的「♡ 关于」按钮', 1)

    # 8) 自检段落补上本版的量测结果
    src = src.replace(
        '界面改动在 880（窗口最窄）、987、1000 三种宽度、浅色 / 深色两种主题下逐一\n'
        '  离屏渲染自检：顶栏均无溢出，右侧状态标签没有被窗口按钮遮挡。',
        '界面改动在 880（窗口最窄）、987、1000 三种宽度、浅色 / 深色两种主题下逐一\n'
        '  离屏渲染自检：顶栏均无溢出，右侧控件没有被窗口按钮遮挡；「关于」按钮与\n'
        '  颜色切换器实测同为 28px 高、上下边界完全对齐。', 1)

    # 9)「怎么确认你用的是新版」跟着改
    src = src.replace(
        '  · 右上角有一个带心形的「关于」按钮，点开能看到「这个工具会一直免费下去」那段话、8 条功能说明，以及微信 / 支付宝两张收款码；\n',
        '  · 右上角有一个带心形的「关于」按钮，位置在颜色切换器（自动 / 浅色 / 深色）的左边，'
        '两者的高度一样、看着是一整块；点开能看到「这个工具会一直免费下去」那段话、'
        '8 条功能说明，以及微信 / 支付宝两张收款码；\n'
        '  · 顶栏右上角没有版本号小标签了（本版去掉的）；版本号看底栏，或看「关于」面板；\n',
        1)

    # 10) 兜底：目录块之外如果还残留 1.2.20 的图片名，一并换掉
    src = re.sub(r'(图标效果|界面效果)-1\.2\.20', r'\1-1.2.21', src)
    src = src.replace('收款码对比-1.2.19', '收款码对比-1.2.21')
    src = src.replace('使用说明-1.2.20', '使用说明-1.2.21')

    io.open(DST, 'w', encoding='utf-8', newline='\n').write(src)
    print('[OK] %s  (%d 行, %d 字符)' % (DST, src.count('\n') + 1, len(src)))


if __name__ == '__main__':
    main()
