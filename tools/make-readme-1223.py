def main():
    src = io.open(SRC, encoding='utf-8').read()

    # 1) 标题版本号
    src = src.replace('Doro 镜像刻录工具 v1.2.22 —— 使用说明',
                      'Doro 镜像刻录工具 v1.2.23 —— 使用说明', 1)
    # 2) 原来的「本版改进」降级为「上一版改进」
    src = src.replace('【本版改进：「关于」面板打开时，右上角不再「穿模」】',
                      '【上一版改进（v1.2.22）：「关于」面板打开时，右上角不再「穿模」】', 1)
    # 3) 插入新的本版改进段落（放在标题下的分隔线之后）
    sep = '=' * 49
    i = src.index(sep)
    j = src.index('\n', i) + 1
    src = src[:j] + '\n\n' + NEW_SECTION + src[j:]
    # 4) 替换整个目录内容块
    s = src.index('【目录内容】')
    e = src.index('【先搞清楚：')
    src = src[:s] + DIR_BLOCK + '\n\n' + src[e:]

    # 5) 底栏版本号（顺带说明 Beta）
    src = src.replace('· 程序底栏显示 v1.2.22；',
                      '· 程序底栏显示 v1.2.23 Beta（版本号后面跟着一个 Beta 小徽章）；', 1)

    # 6)「怎么确认你用的是新版」：更新跨平台判据 + 补本版三条判据
    src = src.replace(
        '  · 右上角不再有写着「Windows」的平台标签（本版已去掉）；'
        '顶栏副标题是「跨平台 · Windows / macOS / Linux」；\n',
        '  · 右上角不再有写着「Windows」的平台标签（本版已去掉）；'
        '顶栏副标题是「跨平台 · Windows / macOS」（Linux 版还没做，只列确实支持的平台）；\n'
        '  · 打开「关于」面板：多了一个「开源」区，写明代码公开、MIT 许可证、'
        '欢迎 Star / Issue / 贡献代码（仓库地址确定前显示「仓库地址即将公布」）；\n'
        '  · 顶栏左上角和「关于」面板里的头像是灰底的，和任务栏图标一个样（不再是白底）；\n',
        1)

    # 7) 兜底：目录块之外如果还残留旧版本图片名，一并换掉
    src = re.sub(r'(图标效果|界面效果|顶栏特写|收款码对比)-1\.2\.22', r'\1-1.2.23', src)
    src = src.replace('使用说明-1.2.22', '使用说明-1.2.23')

    io.open(DST, 'w', encoding='utf-8', newline='\n').write(src)
    print('[OK] %s  (%d 行, %d 字符)' % (DST, src.count('\n') + 1, len(src)))


if __name__ == '__main__':
    main()
