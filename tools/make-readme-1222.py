def main():
    src = io.open(SRC, encoding='utf-8').read()

    # 1) 标题版本号
    src = src.replace('Doro 镜像刻录工具 v1.2.21 —— 使用说明',
                      'Doro 镜像刻录工具 v1.2.22 —— 使用说明', 1)
    # 2) 原来的「本版改进」降级为「上一版改进」
    src = src.replace('【本版改进：顶栏更干净，「关于」和颜色切换并成一块】',
                      '【上一版改进（v1.2.21）：顶栏更干净，「关于」和颜色切换并成一块】', 1)
    # 3) 插入新的本版改进段落（放在标题下的分隔线之后）
    sep = '=' * 49
    i = src.index(sep)
    j = src.index('\n', i) + 1
    src = src[:j] + '\n\n' + NEW_SECTION + src[j:]
    # 4) 替换整个目录内容块
    s = src.index('【目录内容】')
    e = src.index('【先搞清楚：')
    src = src[:s] + DIR_BLOCK + '\n\n' + src[e:]

    # 5) 底栏版本号
    src = src.replace('· 程序底栏显示 v1.2.21；', '· 程序底栏显示 v1.2.22；', 1)

    # 6)「怎么确认你用的是新版」补本版判据
    src = src.replace(
        '  · 任务栏图标 / 窗口左上角图标是 Doro 头像（粉发 + 头顶橘子），不再是默认图标；\n',
        '  · 打开「关于」面板：右上角三个窗口按钮底下不再有一块亮斑，按钮区与周围遮罩颜色一致；'
        '面板的右上圆角完整可见，不被按钮盖掉；关掉面板时也不会闪一下；\n'
        '  · 初始页面底部没有「运行日志」面板（从本版起默认不显示）；点「开始刻录」之后它才出现；\n'
        '  · 任务栏图标 / 窗口左上角图标是 Doro 头像（粉发 + 头顶橘子），不再是默认图标；\n',
        1)

    # 7) 兜底：目录块之外如果还残留 1.2.21 的图片名，一并换掉
    src = re.sub(r'(图标效果|界面效果|顶栏特写|收款码对比)-1\.2\.21', r'\1-1.2.22', src)
    src = re.sub(r'(图标效果|界面效果|顶栏特写|收款码对比)-1\.2\.20', r'\1-1.2.22', src)
    src = src.replace('使用说明-1.2.21', '使用说明-1.2.22')

    io.open(DST, 'w', encoding='utf-8', newline='\n').write(src)
    print('[OK] %s  (%d 行, %d 字符)' % (DST, src.count('\n') + 1, len(src)))


if __name__ == '__main__':
    main()
