import io
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', '_readme_1221.txt')
DST = os.path.join(ROOT, 'tools', '_readme_1222.txt')

NEW_SECTION = """【本版改进：「关于」面板打开时，右上角不再「穿模」】

  ▸ 问题长什么样

    打开「关于」面板（或选中内置硬盘时弹出的那个红色提醒）时，整个界面会压在
    一层半透明遮罩底下。可右上角那三个窗口按钮（最小化 / 最大化 / 关闭）是
    Windows 自己画的一块独立图层，叠在网页之上 —— 遮罩压不到它，于是按钮那一块
    始终是亮的，就像面板「穿」过了遮罩：右上角突兀地亮着一块。

    关掉面板的那一刻也同样：按钮的颜色比周围晚一步变回去，会闪一下。

  ▸ 本版做了三件事

    1. 按钮区跟着遮罩一起变色

       面板一打开，主进程就把按钮区的底色换成「遮罩压在实际界面上的等效颜色」
       （浅色界面下是一块适中的灰，深色界面下是接近黑的深灰），按钮区与周边
       遮罩融为一体。这个颜色不是随手填的：按遮罩的透明度和界面底色算出来之后，
       又拿截图逐像素核对过，误差在 1/255 以内。

    2. 换色与遮罩同一帧完成，不再闪

       换色指令改成「同步」发送，并且在界面绘制的前一刻执行 —— 遮罩出现的那一瞬间，
       按钮区的颜色已经换好了；关面板时也一样，两者一起变，不再有快慢之差。

    3. 面板整体给按钮区让路

       「关于」面板很高，顶边原本会伸到按钮区底下，右上角的圆角和描边被按钮底色
       盖掉一截。现在弹窗整体左移，给按钮区让出整条宽度，圆角和描边完整可见。
       macOS / Linux 没有这个叠层，界面与之前完全一样。

  ▸ 顺带：初始页面不再显示运行日志

    以前一打开软件，底部就放着一条「运行日志」面板（虽然是折叠着的）。现在初始
    页面干干净净，什么日志都不显示；从点下「开始刻录」的那一刻起，日志面板才
    登场，实时滚动写入 / 校验进度。万一刻录失败弹出警告，它也会立刻出现。
"""

