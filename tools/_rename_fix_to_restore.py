for path, pairs in edits.items():
    s = open(path, encoding='utf-8').read()
    n_miss = 0
    for a, b in pairs:
        if a not in s:
            print('!! 未命中 [%s]: %s' % (path, a[:50]))
            n_miss += 1
            continue
        s = s.replace(a, b)
    open(path, 'w', encoding='utf-8').write(s)
    print('OK', path, ('（%d 处未命中）' % n_miss) if n_miss else '')
